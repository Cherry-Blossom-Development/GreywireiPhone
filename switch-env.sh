#!/bin/bash

# Greywire iOS environment switcher
# Usage: ./switch-env.sh [local|dev-test|production]

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_DIR="$SCRIPT_DIR/environments"
CONFIG_FILE="$SCRIPT_DIR/Greywire/Config.swift"

if [ -z "$1" ]; then
    echo "Usage: ./switch-env.sh [local|dev-test|production]"
    echo ""
    echo "Environments:"
    echo "  local       - Local backend (http://localhost:3001)"
    echo "  dev-test    - EC2 dev test (https://test.dev.prosaurus.com)"
    echo "  production  - Production (https://www.prosaurus.com)"
    exit 1
fi

ENV_FILE="$ENV_DIR/$1.env"

if [ ! -f "$ENV_FILE" ]; then
    echo "Error: Environment file not found: $ENV_FILE"
    exit 1
fi

# Read environment variables
source "$ENV_FILE"

# Generate Config.swift
cat > "$CONFIG_FILE" << EOF
import Foundation

// Auto-generated by switch-env.sh - do not edit manually
struct Config {
    static let baseURL = "$BASE_URL"
    static let environment = "$ENVIRONMENT"
}
EOF

echo "Switched to $1 environment"
echo "  BASE_URL: $BASE_URL"
echo ""
echo "Rebuild the app for changes to take effect."
